// Renders the scenario logs written by e2e/run.sh into screenshots and an
// index. Usage: node render.mjs <logs dir> <evidence dir>
import { chromium } from "playwright-core";
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { execSync } from "node:child_process";

const [logsDir, outDir] = process.argv.slice(2);
if (!logsDir || !outDir) {
  console.error("usage: node render.mjs <logs dir> <evidence dir>");
  process.exit(2);
}
mkdirSync(outDir, { recursive: true });

const escapeHtml = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function classify(line) {
  if (line.startsWith("PASS  ")) return "pass";
  if (line.startsWith("FAIL  ")) return "fail";
  if (line.startsWith("SKIP  ")) return "skip";
  if (line.startsWith("# ")) return "note";
  if (line.startsWith("$ ") || /^\[[^\]]+\]\$ /.test(line)) return "cmd";
  if (/^\[exit \d+\]$/.test(line)) return "exit";
  return "out";
}

function page(title, result, lines) {
  const body = lines
    .map((l) => `<div class="${classify(l)}">${escapeHtml(l) || "&nbsp;"}</div>`)
    .join("\n");
  return `<!doctype html>
<html><head><meta charset="utf-8"><style>
  :root { color-scheme: dark; }
  body { margin: 0; background: #0f1419; color: #d6dde6; font: 13px/1.45 ui-monospace, "DejaVu Sans Mono", Menlo, Consolas, monospace; }
  header { padding: 16px 24px; background: #172029; border-bottom: 1px solid #2a3846; display: flex; justify-content: space-between; align-items: center; gap: 16px; }
  h1 { margin: 0; font-size: 15px; font-weight: 600; color: #f0f4f8; }
  .badge { padding: 3px 12px; border-radius: 4px; font-weight: 700; letter-spacing: .04em; }
  .badge.PASS { background: #1f6f43; color: #e6fff1; }
  .badge.FAIL { background: #9b2c2c; color: #ffecec; }
  .badge.SKIP { background: #8a6d1b; color: #fff6dc; }
  main { padding: 16px 24px 24px; width: 1150px; box-sizing: border-box; }
  main div { white-space: pre-wrap; word-break: break-word; }
  .cmd { color: #7dd3fc; font-weight: 600; margin-top: 10px; }
  .out { color: #c3ccd6; }
  .exit { color: #6b7a89; font-size: 11px; }
  .note { color: #a5b4c3; font-style: italic; margin-top: 10px; }
  .pass { color: #6ee7a0; font-weight: 600; }
  .fail { color: #ff8a8a; font-weight: 700; }
  .skip { color: #f5d06f; font-weight: 600; }
</style></head><body>
<header><h1>${escapeHtml(title)}</h1><span class="badge ${result}">${result}</span></header>
<main>${body}</main>
</body></html>`;
}

const files = readdirSync(logsDir)
  .filter((f) => /^\d\d-.*\.log$/.test(f))
  .sort();

const launchOpts = {};
if (process.env.CHROMIUM_PATH) {
  launchOpts.executablePath = process.env.CHROMIUM_PATH;
} else if (existsSync("/opt/pw-browsers")) {
  const dirs = readdirSync("/opt/pw-browsers").filter((d) => /^chromium-\d+$/.test(d));
  if (dirs.length) launchOpts.executablePath = join("/opt/pw-browsers", dirs[0], "chrome-linux", "chrome");
}
launchOpts.args = ["--no-sandbox"];
const browser = await chromium.launch(launchOpts);
const context = await browser.newContext({ viewport: { width: 1150, height: 400 }, deviceScaleFactor: 1 });

const rows = [];
for (const f of files) {
  const lines = readFileSync(join(logsDir, f), "utf8").split("\n");
  if (lines.at(-1) === "") lines.pop();
  const titleLine = lines.find((l) => l.startsWith("TITLE ")) ?? `TITLE ${f}`;
  const title = titleLine.slice(6);
  const resultLine = lines.find((l) => l.startsWith("RESULT "));
  const result = resultLine ? resultLine.slice(7).trim() : "FAIL";
  const shown = lines.filter((l) => !l.startsWith("TITLE ") && !l.startsWith("RESULT "));

  const p = await context.newPage();
  await p.setContent(page(title, result, shown));
  const png = f.replace(/\.log$/, ".png");
  await p.screenshot({ path: join(outDir, png), fullPage: true });
  await p.close();

  const checks = shown.filter((l) => l.startsWith("PASS  ")).length;
  const failed = shown.filter((l) => l.startsWith("FAIL  ")).length;
  rows.push({ png, title, result, checks, failed });
  console.log(`${result.padEnd(4)} ${png}`);
}
await browser.close();

const sh = (cmd) => {
  try {
    return execSync(cmd, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "unknown";
  }
};
const total = rows.reduce((n, r) => n + r.checks, 0);
const totalFailed = rows.reduce((n, r) => n + r.failed, 0);
const md = [
  "# End-to-end evidence",
  "",
  "Generated by `e2e/run.sh` and `e2e/render/render.mjs`. Every screenshot is a rendered",
  "terminal session of a scenario run against real Docker and nftables; nothing is edited by hand.",
  "",
  `- commit: \`${sh("git rev-parse --short HEAD")}\``,
  `- date: ${new Date().toISOString()}`,
  `- kernel: \`${sh("uname -r")}\``,
  `- docker: \`${sh("docker version --format '{{.Server.Version}}'")}\``,
  `- IPv6 scenarios: ${process.env.E2E_IPV6 === "1" ? "run" : "not run (Docker daemon without IPv6)"}`,
  `- checks: ${total} passed, ${totalFailed} failed`,
  "",
  "| # | Scenario | Result | Checks |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.png.slice(0, 2)} | [${r.title.replace(/^\d+\s+/, "")}](${r.png}) | ${r.result} | ${r.checks} |`),
  "",
  ...rows.flatMap((r) => [`### ${r.title}`, "", `![${r.title}](${r.png})`, ""]),
].join("\n");
writeFileSync(join(outDir, "INDEX.md"), md);
process.exit(totalFailed > 0 ? 1 : 0);
